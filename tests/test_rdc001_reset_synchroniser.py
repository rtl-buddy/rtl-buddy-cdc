"""RDC-001 and a reset synchroniser's own flops (rtl-buddy-cdc#367).

A reset generated by a register in another clock domain has to be
synchronised into the destination, and the synchroniser's flops take
that foreign reset on their own async pin by design. RDC-001 used to
fire on them. It now exempts members of a recognised reset synchroniser
(``ctx.reset_synchronizers``) whose chain deasserts correctly, and
nothing else:

- ``good_reset_sync_foreign_reg``: the issue's reproducer, clean.
- ``bad_reset_sync_foreign_reg``: a single-stage "synchroniser", a
  two-stage chain whose head loads the asserted value, and an ordinary
  flop on the raw foreign reset beside a correct synchroniser. All three
  still fire, and the third is reported on the ordinary flop only.
"""

from __future__ import annotations

from pathlib import Path

from rtl_buddy_cdc import netlist, sdc as sdc_mod
from rtl_buddy_cdc.netlist import Module
from rtl_buddy_cdc.rules import Violation, check_rdc_001, run_all

FIX = Path(__file__).parent / "fixtures"


def _load(name: str) -> tuple[Module, sdc_mod.ClockSpec]:
    module = netlist.load(FIX / name / f"{name}.json")
    spec = sdc_mod.parse_file(FIX / name / f"{name}.sdc")
    return module, spec


def _q_name(module: Module, cell_name: str) -> str:
    """The register a flop cell drives, by its ``Q`` netname."""
    q = tuple(module.cells[cell_name].connections["Q"])
    names = sorted(n.name for n in module.netnames.values() if tuple(n.bits) == q)
    assert names, cell_name
    return names[0]


def _by_reg(module: Module, violations: list[Violation]) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for v in violations:
        out.setdefault(v.rule_id, []).append(_q_name(module, v.cell_name or ""))
    return {k: sorted(vs) for k, vs in out.items()}


def test_synchroniser_of_a_foreign_register_reset_is_clean() -> None:
    module, spec = _load("good_reset_sync_foreign_reg")
    assert run_all(module, [], spec) == []


def test_unsynchronised_foreign_resets_still_fire() -> None:
    module, spec = _load("bad_reset_sync_foreign_reg")
    got = _by_reg(module, run_all(module, [], spec))
    assert got == {
        # The single stage; the backwards chain (one finding for both
        # stages, reported on the first by cell name); the ordinary flop.
        "RDC-001": ["q3_raw", "single", "w0"],
        "RDC-007": ["w1"],
    }


def test_finding_lists_only_the_non_synchroniser_flop() -> None:
    """The a3 reset drives a correct synchroniser and ``q3_raw``: the
    finding names ``q3_raw`` alone, not the synchroniser stages."""
    module, spec = _load("bad_reset_sync_foreign_reg")
    [v] = [
        v
        for v in check_rdc_001(module, [], spec)
        if _q_name(module, v.cell_name or "") == "q3_raw"
    ]
    assert "destination flop:" in v.message
    assert "share this source" not in v.message


def test_backwards_chain_lists_both_stages() -> None:
    module, spec = _load("bad_reset_sync_foreign_reg")
    [v] = [
        v
        for v in check_rdc_001(module, [], spec)
        if _q_name(module, v.cell_name or "") == "w0"
    ]
    assert "2 destination flops share this source" in v.message
